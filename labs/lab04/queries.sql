-- 1. Фамилии и даты ведомостей, RIGHT JOIN.
SELECT l."ФАМИЛИЯ", v."ДАТА"
FROM "Н_ЛЮДИ" l
RIGHT JOIN "Н_ВЕДОМОСТИ" v ON l."ИД" = v."ЧЛВК_ИД"
WHERE l."ИМЯ" < 'Роман'
  AND v."ИД" < 1250972;

-- 2. Люди, обучения и группы, INNER JOIN.
SELECT l."ИД", o."ЧЛВК_ИД", u."ГРУППА"
FROM "Н_ЛЮДИ" l
INNER JOIN "Н_ОБУЧЕНИЯ" o ON l."ИД" = o."ЧЛВК_ИД"
INNER JOIN "Н_УЧЕНИКИ" u ON l."ИД" = u."ЧЛВК_ИД"
WHERE l."ОТЧЕСТВО" < 'Александрович'
  AND o."НЗК" > '001000'
  AND u."ИД" > 100410;
