-- 1. Типы ведомостей и ведомости.
SELECT t."НАИМЕНОВАНИЕ", v."ЧЛВК_ИД"
FROM "Н_ТИПЫ_ВЕДОМОСТЕЙ" t
LEFT JOIN "Н_ВЕДОМОСТИ" v ON t."ИД" = v."ТВ_ИД"
WHERE t."НАИМЕНОВАНИЕ" > 'Экзаменационный лист'
  AND v."ЧЛВК_ИД" = 117219;

-- 2. Люди, обучения и ученики.
SELECT l."ФАМИЛИЯ", o."НЗК", u."ГРУППА"
FROM "Н_ЛЮДИ" l
LEFT JOIN "Н_ОБУЧЕНИЯ" o ON l."ИД" = o."ЧЛВК_ИД"
LEFT JOIN "Н_УЧЕНИКИ" u ON o."ЧЛВК_ИД" = u."ЧЛВК_ИД"
WHERE l."ИД" = 100012
  AND o."НЗК" < '001000'
  AND u."ГРУППА" > '1100';

-- 3. Студенты вечерней формы без ИНН.
SELECT CASE
    WHEN COUNT(*) > 0 THEN 'Да'
    ELSE 'Нет'
END AS has_students_without_inn
FROM "Н_ЛЮДИ" l
JOIN "Н_ОБУЧЕНИЯ" o ON l."ИД" = o."ЧЛВК_ИД"
JOIN "Н_УЧЕНИКИ" u ON o."ЧЛВК_ИД" = u."ЧЛВК_ИД"
JOIN "Н_ПЛАНЫ" p ON p."ИД" = u."ПЛАН_ИД"
JOIN "Н_ФОРМЫ_ОБУЧЕНИЯ" f ON f."ИД" = p."ФО_ИД"
WHERE f."НАИМЕНОВАНИЕ" = 'Очно-заочная(вечерняя)'
  AND l."ИНН" IS NULL;

-- 4. Планы очной формы с менее чем двумя группами.
SELECT "ПЛАН_ИД"
FROM "Н_ГРУППЫ_ПЛАНОВ"
WHERE "ПЛАН_ИД" IN (
    SELECT p."ИД"
    FROM "Н_ПЛАНЫ" p
    JOIN "Н_ФОРМЫ_ОБУЧЕНИЯ" f ON p."ФО_ИД" = f."ИД"
    WHERE f."НАИМЕНОВАНИЕ" = 'Очная'
)
GROUP BY "ПЛАН_ИД"
HAVING COUNT(DISTINCT "ГРУППА") < 2;

-- 5. Средние оценки студентов группы 4100.
SELECT l."ИД", l."ФАМИЛИЯ", l."ИМЯ", l."ОТЧЕСТВО",
       ROUND(AVG(v."ОЦЕНКА"::numeric), 2) AS "ср_оценка"
FROM "Н_ЛЮДИ" l
JOIN "Н_ВЕДОМОСТИ" v ON l."ИД" = v."ЧЛВК_ИД"
JOIN "Н_УЧЕНИКИ" u ON l."ИД" = u."ЧЛВК_ИД"
WHERE u."ГРУППА" = '4100'
  AND v."ОЦЕНКА" ~ '^[0-9]+$'
GROUP BY l."ИД", l."ФАМИЛИЯ", l."ИМЯ", l."ОТЧЕСТВО"
HAVING AVG(v."ОЦЕНКА"::numeric) > (
    SELECT AVG(v2."ОЦЕНКА"::numeric)
    FROM "Н_ВЕДОМОСТИ" v2
    JOIN "Н_УЧЕНИКИ" u2 ON v2."ЧЛВК_ИД" = u2."ЧЛВК_ИД"
    WHERE u2."ГРУППА" = '1100'
      AND v2."ОЦЕНКА" ~ '^[0-9]+$'
);

-- 6. Студенты, отчисленные до 1 сентября 2012 года.
SELECT u."ГРУППА", l."ИД", l."ФАМИЛИЯ", l."ИМЯ", l."ОТЧЕСТВО",
       u."П_ПРКОК_ИД"
FROM "Н_ЛЮДИ" l
JOIN "Н_УЧЕНИКИ" u ON l."ИД" = u."ЧЛВК_ИД"
WHERE u."ПРИЗНАК" = 'Отчисл'
  AND u."КОНЕЦ_ПО_ПРИКАЗУ" < DATE '2012-09-01'
  AND u."ПЛАН_ИД" IN (
      SELECT p."ИД"
      FROM "Н_ПЛАНЫ" p
      JOIN "Н_ФОРМЫ_ОБУЧЕНИЯ" f ON p."ФО_ИД" = f."ИД"
      JOIN "Н_НАПРАВЛЕНИЯ_СПЕЦИАЛ" ns ON p."НАПС_ИД" = ns."ИД"
      JOIN "Н_НАПР_СПЕЦ" n ON ns."НС_ИД" = n."ИД"
      WHERE f."НАИМЕНОВАНИЕ" IN ('Очная', 'Заочная')
        AND n."НАИМЕНОВАНИЕ" LIKE '%Программная инженерия%'
  );

-- 7. Студенты-однофамильцы с разными датами рождения.
SELECT l1."ИД", l1."ФАМИЛИЯ", l1."ИМЯ", l1."ОТЧЕСТВО", l1."ДАТА_РОЖДЕНИЯ"
FROM "Н_ЛЮДИ" l1
WHERE EXISTS (
    SELECT 1
    FROM "Н_УЧЕНИКИ" u1
    WHERE u1."ЧЛВК_ИД" = l1."ИД"
)
AND EXISTS (
    SELECT 1
    FROM "Н_ЛЮДИ" l2
    WHERE l2."ФАМИЛИЯ" = l1."ФАМИЛИЯ"
      AND l2."ДАТА_РОЖДЕНИЯ" <> l1."ДАТА_РОЖДЕНИЯ"
      AND l2."ИД" <> l1."ИД"
      AND EXISTS (
          SELECT 1
          FROM "Н_УЧЕНИКИ" u2
          WHERE u2."ЧЛВК_ИД" = l2."ИД"
      )
)
ORDER BY l1."ФАМИЛИЯ", l1."ДАТА_РОЖДЕНИЯ", l1."ИД";
